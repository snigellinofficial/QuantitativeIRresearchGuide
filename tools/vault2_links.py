def _hash(text):
    return int(hashlib.md5(text.encode("utf-8")).hexdigest()[:8], 16)


def paper_keywords(design):
    hits = []
    for key, patterns, _disp, _w in KEYWORDS:
        if any(p in design for p in patterns):
            hits.append(key)
    return hits[:2]


def _kw_reason(a, b, kw, avoid=()):
    bank = KW_CLAUSE[kw]
    idx = _hash("%s-%s-%s" % (a, b, kw)) % len(bank)
    for step in range(len(bank)):
        text = "因为识别逻辑相同，两者同为%s，%s" % (
            KW_DISPLAY[kw], bank[(idx + step) % len(bank)])
        if text not in avoid:
            return text
    return text


def _kind_reason(a, b, kind, avoid=()):
    bank = KIND_CLAUSE[kind]
    idx = _hash("%s-%s-%s" % (a, b, kind)) % len(bank)
    for step in range(len(bank)):
        text = "因为数据形态相同，两者同为%s，%s" % (kind, bank[(idx + step) % len(bank)])
        if text not in avoid:
            return text
    return text


def build_edges(papers, order):
    """papers 为题录字典，order 为输出顺序。返回边表。"""
    kw = {pid: paper_keywords(papers[pid]["design"]) for pid in order}
    degree = {pid: 0 for pid in order}
    edges = []
    used = set()

    def add(a, b, cat, ra, rb):
        edges.append({"a": a, "b": b, "cat": cat, "ra": ra, "rb": rb})
        used.add((a, b))
        used.add((b, a))
        degree[a] += 1
        degree[b] += 1

    for a, b, ra, rb in CURATED:
        assert a in papers and b in papers, "配对越界 %s-%s" % (a, b)
        add(a, b, "互为稳健性检验", "因为互为稳健性检验，" + ra, "因为互为稳健性检验，" + rb)

    order_index = {k: i for i, (k, _p, _d, _w) in enumerate(KEYWORDS)}
    weight = {k: w for k, _p, _d, w in KEYWORDS}

    scored = []
    for i, a in enumerate(order):
        for b in order[i + 1:]:
            if (a, b) in used:
                continue
            shared = [k for k in kw[a] if k in kw[b]]
            same_kind = papers[a]["data_kind"] == papers[b]["data_kind"]
            if not shared and not same_kind:
                continue
            score = sum(weight[k] for k in shared) + (4 if same_kind else 0)
            if papers[a]["topic"] == papers[b]["topic"]:
                score += 1
            priority = min([order_index[k] for k in shared] or [99])
            scored.append((-score, priority, a, b, shared, same_kind))
    scored.sort()

    for cap in (4, 5):
        for _neg, _pri, a, b, shared, same_kind in scored:
            if degree[a] >= 3 and degree[b] >= 3:
                continue
            if degree[a] >= cap or degree[b] >= cap:
                continue
            if (a, b) in used:
                continue
            used_a = {e["ra"] for e in edges if e["a"] == a}
            used_b = {e["rb"] for e in edges if e["b"] == b}
            if shared:
                cat = "识别逻辑相同"
                ra = _kw_reason(a, b, shared[0], avoid=used_a)
                rb = _kw_reason(b, a, shared[0], avoid=used_b | {ra})
            else:
                cat = "数据形态相同"
                ra = _kind_reason(a, b, papers[a]["data_kind"], avoid=used_a)
                rb = _kind_reason(b, a, papers[b]["data_kind"], avoid=used_b | {ra})
            add(a, b, cat, ra, rb)

    for pid in order:
        assert 3 <= degree[pid] <= 5, "%s 关联数 %d 越界" % (pid, degree[pid])
    return edges


def adjacency(edges):
    adj = {}
    for e in edges:
        adj.setdefault(e["a"], {})[e["b"]] = (e["cat"], e["ra"])
        adj.setdefault(e["b"], {})[e["a"]] = (e["cat"], e["rb"])
    return adj
